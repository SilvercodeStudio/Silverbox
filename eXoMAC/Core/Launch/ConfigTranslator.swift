import Foundation

nonisolated public struct ConfigTranslation: Sendable, Hashable {
    public var document: DOSBoxConfigDocument
    public var notes: [String]
    /// Overlay folders that must exist before the emulator starts.
    public var overlayFolders: [URL]

    public init(document: DOSBoxConfigDocument, notes: [String] = [], overlayFolders: [URL] = []) {
        self.document = document
        self.notes = notes
        self.overlayFolders = overlayFolders
    }
}

/// Turns an eXoDOS game config (written for DOSBox 0.74, ECE, SVN Daum,
/// DOSBox-X or DOSBox Staging 0.80/0.81 on Windows) into one a Mac emulator
/// accepts.
///
/// The translation keeps the emulation settings that matter (machine, memory,
/// CPU, sound cards, MIDI, autoexec) and drops Windows-only or obsolete
/// keys. Relative paths become absolute paths under the library root.
nonisolated public struct ConfigTranslator: Sendable {
    public let root: LibraryRoot
    public let emulator: EmulatorKind
    public let options: LaunchOptions
    /// True when the emulator can render General MIDI with FluidSynth.
    public let fluidSynthAvailable: Bool
    /// Folders tried for relative autoexec paths that are not under `eXo/`.
    public let fallbackDirectories: [URL]
    /// Host path prefixes to replace, for games unpacked in the local store.
    public let pathMappings: [PathMapping]
    /// Writable overlay for games unpacked on a read-only library.
    public let overlay: OverlayMount?

    public init(root: LibraryRoot, emulator: EmulatorKind, options: LaunchOptions,
                fluidSynthAvailable: Bool = false, fallbackDirectories: [URL] = [],
                pathMappings: [PathMapping] = [], overlay: OverlayMount? = nil) {
        self.root = root
        self.emulator = emulator
        self.options = options
        self.fluidSynthAvailable = fluidSynthAvailable
        self.fallbackDirectories = fallbackDirectories
        self.pathMappings = pathMappings
        self.overlay = overlay
    }

    public func translate(_ source: DOSBoxConfigDocument) -> ConfigTranslation {
        var output = DOSBoxConfigDocument(header: ["Generated by eXoMAC for \(emulator.displayName). Edits are overwritten at every launch."])
        var notes: [String] = []
        var overlayFolders: [URL] = []
        let autoexec = AutoexecRewriter(baseDirectory: root.eXoDirectory, fallbackDirectories: fallbackDirectories,
                                        mappings: pathMappings, overlay: overlay)

        for section in source.sections {
            if section.isAutoexec {
                let result = autoexec.rewrite(section.lines)
                output.autoexecLines = result.lines
                notes.append(contentsOf: result.notes)
                overlayFolders = result.overlayFolders
                continue
            }
            for entry in section.entries {
                let outcomes: [Outcome]
                switch emulator {
                case .dosboxStaging: outcomes = stagingOutcome(section: section.name, key: entry.key, value: entry.value)
                case .dosboxX: outcomes = dosboxXOutcome(section: section.name, key: entry.key, value: entry.value)
                }
                for outcome in outcomes {
                    switch outcome {
                    case .set(let s, let k, let v): output.set(s, k, v)
                    case .drop(let note): if let note { notes.append(note) }
                    }
                }
            }
        }

        applyOptions(to: &output, notes: &notes)
        var unique: [String] = []
        for note in notes where !unique.contains(note) { unique.append(note) }
        return ConfigTranslation(document: output, notes: unique, overlayFolders: overlayFolders)
    }

    nonisolated enum Outcome: Hashable, Sendable {
        case set(String, String, String)
        case drop(String?)
    }

    // MARK: - DOSBox Staging 0.83

    private static let stagingMachines: Set<String> = ["hercules", "cga", "cga_mono", "tandy", "pcjr", "ega", "svga_s3",
                                                       "svga_et3000", "svga_et4000", "svga_paradise", "vesa_nolfb", "vesa_oldvbe"]

    /// Keys that pass through unchanged, per section. Covers both the classic
    /// DOSBox keys and the Staging 0.80/0.81 keys eXoDOS already uses.
    private static let stagingPassThrough: [String: Set<String>] = [
        "sdl": ["texture_renderer", "window_size", "window_position", "window_decorations", "vsync", "presentation_mode",
                "host_rate", "pause_when_inactive", "mute_when_inactive", "keyboard_capture"],
        "dosbox": ["memsize", "vmemsize", "vmem_delay", "dos_rate", "vesa_modes", "mcb_fault_strategy", "allow_write_protected_files"],
        "render": ["integer_scaling", "viewport", "monochrome_palette", "cga_colors", "color_space", "image_adjustments",
                   "crt_color_profile", "brightness", "contrast", "gamma", "saturation", "deinterlacing", "dedithering"],
        "composite": ["composite", "era", "hue", "convergence"],
        "cpu": ["cycleup", "cycledown", "cpu_cycles_protected", "cpu_throttle", "cpu_idle"],
        "voodoo": ["voodoo", "voodoo_memsize", "voodoo_threads", "voodoo_bilinear_filtering"],
        "capture": ["default_image_capture_formats"],
        "mouse": ["mouse_capture", "mouse_middle_release", "mouse_multi_display_aware", "mouse_sensitivity", "mouse_raw_input",
                  "builtin_dos_mouse_driver", "builtin_dos_mouse_driver_model", "com_mouse_model", "vmware_mouse", "virtualbox_mouse"],
        "mixer": ["nosound", "rate", "blocksize", "prebuffer", "negotiate", "compressor", "crossfeed", "reverb", "chorus"],
        "mt32": ["model"],
        "fluidsynth": ["soundfont_volume", "fsynth_chorus", "fsynth_reverb", "fsynth_filter"],
        "soundcanvas": ["soundcanvas_model", "soundcanvas_filter"],
        "midi": ["midiconfig", "raw_midi_output"],
        "sblaster": ["sbtype", "sbbase", "irq", "dma", "hdma", "sbmixer", "sbwarmup", "sb_filter", "sb_filter_always_on",
                     "oplmode", "opl_fadeout", "opl_filter", "cms", "cms_filter"],
        "gus": ["gus", "gusbase", "gusirq", "gusdma", "gus_filter", "ultradir"],
        "imfc": ["imfc", "imfc_base", "imfc_irq", "imfc_filter"],
        "innovation": ["innovation", "innovation_sid_filter", "innovation_filter"],
        "speaker": ["lpt_dac", "lpt_dac_filter", "pcspeaker", "pcspeaker_filter", "tandy", "tandy_fadeout", "tandy_filter", "tandy_dac_filter"],
        "reelmagic": ["reelmagic", "reelmagic_key", "reelmagic_fcode"],
        "joystick": ["joysticktype", "timed", "autofire", "buttonwrap", "circularinput", "deadzone", "use_joy_calibration_hotkeys"],
        "serial": ["serial1", "serial2", "serial3", "serial4", "phonebookfile"],
        "dos": ["xms", "ems", "umb", "ver", "country", "keyboard_layout", "locale_period", "expand_shell_variable", "file_locking"],
        "ipx": ["ipx"],
        "ethernet": ["nicbase", "nicirq", "macaddr", "tcp_port_forwards", "udp_port_forwards"],
    ]

    func stagingOutcome(section: String, key: String, value: String) -> [Outcome] {
        let v = value.trimmingCharacters(in: .whitespaces)
        if Self.stagingPassThrough[section]?.contains(key) == true {
            return [.set(section, key, v)]
        }
        switch (section, key) {
        // [sdl]: Staging has its own window and output model.
        case ("sdl", "fullscreen"): return [.drop(nil)]
        case ("sdl", "sensitivity"): return [.set("mouse", "mouse_sensitivity", v)]
        case ("sdl", "autolock"): return Self.isFalse(v) ? [.set("mouse", "mouse_capture", "seamless")] : [.drop(nil)]
        case ("sdl", _): return [.drop(nil)]

        case ("dosbox", "machine"):
            let lowered = v.lowercased()
            if Self.stagingMachines.contains(lowered) { return [.set("dosbox", "machine", lowered)] }
            if lowered == "vgaonly" { return [.set("dosbox", "machine", "svga_paradise"), .drop("machine=vgaonly is not available; using svga_paradise, the closest plain VGA.")] }
            if lowered.hasPrefix("cga") { return [.set("dosbox", "machine", "cga"), .drop("machine=\(v) mapped to cga; composite output is configured in [composite].")] }
            if lowered.hasPrefix("tandy") { return [.set("dosbox", "machine", "tandy")] }
            if lowered.hasPrefix("pcjr") { return [.set("dosbox", "machine", "pcjr")] }
            return [.set("dosbox", "machine", "svga_s3"), .drop("machine=\(v) is unknown to DOSBox Staging; using svga_s3.")]
        case ("dosbox", _): return [.drop(nil)]

        case ("render", "aspect"):
            if Self.isTrue(v) { return [.set("render", "aspect", "on")] }
            if Self.isFalse(v) { return [.set("render", "aspect", "off")] }
            return [.set("render", "aspect", v)]
        case ("render", "scaler"):
            let name = v.replacingOccurrences(of: "forced", with: "").trimmingCharacters(in: .whitespaces)
            if name.isEmpty || name == "none" || name.hasPrefix("normal") { return [.drop(nil)] }
            return [.drop("Scaler \(name) is not available in DOSBox Staging; a shader is used instead.")]
        case ("render", "glshader"), ("render", "shader"):
            // The options layer decides the shader; keep a note so the user knows.
            return [.drop(v.lowercased() == "none" || v.lowercased().hasPrefix("crt") || v.lowercased() == "sharp" ? nil : "Shader \(v) from the game config was replaced by the shader chosen in Settings.")]
        case ("render", "pixelshader"), ("render", "frameskip"): return [.drop(nil)]
        case ("render", _): return [.drop(nil)]

        case ("composite", _): return [.drop(nil)]

        case ("cpu", "core"):
            let lowered = v.lowercased()
            if ["auto", "dynamic", "normal", "simple"].contains(lowered) { return [.set("cpu", "core", lowered)] }
            if lowered.hasPrefix("dynamic") { return [.set("cpu", "core", "dynamic")] }
            if lowered == "full" { return [.set("cpu", "core", "normal")] }
            return [.set("cpu", "core", "auto"), .drop("core=\(v) is unknown; using auto.")]
        case ("cpu", "cputype"):
            let lowered = v.lowercased()
            switch lowered {
            case "auto", "386", "386_fast", "386_prefetch", "486", "pentium", "pentium_mmx": return [.set("cpu", "cputype", lowered)]
            case "386_slow": return [.set("cpu", "cputype", "386")]
            case "486_slow": return [.set("cpu", "cputype", "486")]
            case "486_prefetch": return [.set("cpu", "cputype", "386_prefetch"), .drop("cputype=486_prefetch mapped to 386_prefetch.")]
            case "pentium_slow": return [.set("cpu", "cputype", "pentium")]
            case "ppro_slow", "pentium_pro", "pentium_ii", "pentium_iii": return [.set("cpu", "cputype", "pentium_mmx")]
            default: return [.set("cpu", "cputype", "auto"), .drop("cputype=\(v) is unknown; using auto.")]
            }
        case ("cpu", "cycles"), ("cpu", "cpu_cycles"): return stagingCyclesOutcomes(v)
        case ("cpu", _): return [.drop(nil)]

        case ("mixer", _): return [.drop(nil)]

        case ("midi", "mididevice"): return midiDeviceOutcomes(v)
        case ("midi", "mt32.romdir"), ("mt32", "romdir"): return [.set("mt32", "romdir", absolutePath(v))]
        case ("midi", "mt32.model"): return [.set("mt32", "model", v)]
        case ("midi", "fluid.soundfont"), ("fluidsynth", "soundfont"): return [.set("fluidsynth", "soundfont", soundFontPath(v))]
        case ("fluidsynth", "chorus"): return [.set("fluidsynth", "fsynth_chorus", v)]
        case ("fluidsynth", "reverb"): return [.set("fluidsynth", "fsynth_reverb", v)]
        case ("fluidsynth", "filter"): return [.set("fluidsynth", "fsynth_filter", v)]
        case ("midi", _), ("mt32", _), ("fluidsynth", _), ("soundcanvas", _): return [.drop(nil)]

        case ("sblaster", _), ("gus", _), ("imfc", _), ("reelmagic", _), ("joystick", _), ("serial", _), ("ipx", _), ("ethernet", _), ("capture", _):
            return [.drop(nil)]

        case ("innovation", "sidmodel"): return [.set("innovation", "innovation", v)]
        case ("innovation", _): return [.drop(nil)]

        case ("mouse", "dos_mouse_driver"): return [.set("mouse", "builtin_dos_mouse_driver", v)]
        case ("mouse", _): return [.drop(nil)]

        case ("speaker", "disney"): return [.set("speaker", "lpt_dac", Self.isTrue(v) ? "disney" : "none")]
        case ("speaker", _): return [.drop(nil)]

        case ("dos", "keyboardlayout"): return [.set("dos", "keyboard_layout", v)]
        case ("dos", _): return [.drop(nil)]

        case ("glide", "glide"):
            if Self.isTrue(v) || v.lowercased() == "emu" {
                return [.set("voodoo", "voodoo", "on"),
                        .drop("This game uses 3dfx Glide. eXoDOS relies on a Glide pass-through build; DOSBox Staging emulates a Voodoo card instead, so results may differ. DOSBox-X is the alternative.")]
            }
            return [.drop(nil)]
        case ("pci", _), ("glide", _), ("voodoo", _): return [.drop(nil)]

        default:
            return [.drop("Setting [\(section)] \(key) is not available in DOSBox Staging and was dropped.")]
        }
    }

    /// DOSBox Staging 0.83 split `cycles` into real-mode `cpu_cycles` and
    /// `cpu_cycles_protected`, and dropped `auto`. Classic `auto` meant 3000
    /// cycles in real mode and as many as possible in protected mode.
    private func stagingCyclesOutcomes(_ value: String) -> [Outcome] {
        let lowered = value.lowercased().trimmingCharacters(in: .whitespaces)
        if lowered == "auto" || lowered.hasPrefix("auto ") {
            return [.set("cpu", "cpu_cycles", "3000"), .set("cpu", "cpu_cycles_protected", "max")]
        }
        if lowered.hasPrefix("max") {
            return [.set("cpu", "cpu_cycles", lowered), .set("cpu", "cpu_cycles_protected", "auto")]
        }
        if lowered.hasPrefix("fixed ") {
            return [.set("cpu", "cpu_cycles", String(lowered.dropFirst(6)).trimmingCharacters(in: .whitespaces)),
                    .set("cpu", "cpu_cycles_protected", "auto")]
        }
        if Int(lowered) != nil {
            return [.set("cpu", "cpu_cycles", lowered), .set("cpu", "cpu_cycles_protected", "auto")]
        }
        return [.set("cpu", "cpu_cycles", "3000"), .set("cpu", "cpu_cycles_protected", "max"),
                .drop("cycles=\(value) is not understood; using 3000 real-mode cycles and max protected-mode cycles.")]
    }

    private func midiDeviceOutcomes(_ value: String) -> [Outcome] {
        let lowered = value.lowercased()
        switch lowered {
        case "mt32": return [.set("midi", "mididevice", "mt32"), .set("mt32", "romdir", root.mt32Directory.path)]
        case "none", "off": return [.set("midi", "mididevice", "none")]
        case "fluidsynth", "synth":
            if emulator == .dosboxStaging, !fluidSynthAvailable {
                return [.set("midi", "mididevice", "coreaudio"), .drop("FluidSynth is not available to DOSBox Staging on this Mac; using the macOS synthesizer for General MIDI.")]
            }
            return [.set("midi", "mididevice", "fluidsynth")]
        case "coreaudio", "coremidi": return [.set("midi", "mididevice", lowered)]
        case "soundcanvas": return [.set("midi", "mididevice", "soundcanvas")]
        default:
            // default, auto, win32, alsa, oss, port: the host's General MIDI device.
            return generalMIDIOutcomes()
        }
    }

    private func generalMIDIOutcomes() -> [Outcome] {
        var choice = options.generalMIDI
        if choice == .automatic {
            choice = fluidSynthAvailable ? .fluidSynthSoundCanvas : .coreAudio
        }
        switch choice {
        case .fluidSynthSoundCanvas:
            let soundFont = root.mt32Directory.appendingPathComponent("SoundCanvas.sf2").path
            switch emulator {
            case .dosboxStaging:
                return [.set("midi", "mididevice", "fluidsynth"), .set("fluidsynth", "soundfont", soundFont)]
            case .dosboxX:
                return [.set("midi", "mididevice", "fluidsynth"), .set("midi", "fluid.soundfont", soundFont)]
            }
        case .coreAudio, .automatic:
            return [.set("midi", "mididevice", "coreaudio")]
        }
    }

    // MARK: - DOSBox-X

    func dosboxXOutcome(section: String, key: String, value: String) -> [Outcome] {
        let v = value.trimmingCharacters(in: .whitespaces)
        switch (section, key) {
        case ("sdl", "fullscreen"), ("sdl", "mapperfile"), ("sdl", "fulldouble"): return [.drop(nil)]
        case ("sdl", "output"):
            let lowered = v.lowercased()
            return ["surface", "opengl", "openglnb", "openglpp", "ttf", "texture", "texturenb"].contains(lowered)
                ? [.set("sdl", "output", lowered)] : [.set("sdl", "output", "openglnb")]
        case ("midi", "mididevice"): return midiDeviceOutcomes(v)
        case ("midi", "mt32.romdir"), ("mt32", "romdir"): return [.set("midi", "mt32.romdir", absolutePath(v))]
        case ("midi", "fluid.soundfont"), ("fluidsynth", "soundfont"): return [.set("midi", "fluid.soundfont", soundFontPath(v))]
        case ("render", "glshader"), ("render", "pixelshader"), ("render", "shader"): return [.drop(nil)]
        case ("cpu", "cpu_cycles"): return [.set("cpu", "cycles", v)]
        case ("dosbox", "captures"): return [.drop(nil)]
        default:
            return [.set(section, key, v)]
        }
    }

    // MARK: - Options layer

    private func applyOptions(to document: inout DOSBoxConfigDocument, notes: inout [String]) {
        switch emulator {
        case .dosboxStaging:
            document.set("sdl", "fullscreen", options.fullscreen ? "on" : "off")
            if options.windowSize != .default { document.set("sdl", "window_size", options.windowSize.rawValue) }
            switch options.aspect {
            case .gameConfig: break
            case .on: document.set("render", "aspect", "on")
            case .off: document.set("render", "aspect", "off")
            }
            document.set("render", "shader", options.shader.rawValue)
            if options.quietStartup { document.set("dosbox", "startup_verbosity", "quiet") }
        case .dosboxX:
            document.set("sdl", "fullscreen", options.fullscreen ? "true" : "false")
            switch options.windowSize {
            case .default: break
            case .small: document.set("sdl", "windowresolution", "640x480")
            case .medium: document.set("sdl", "windowresolution", "1280x960")
            case .large: document.set("sdl", "windowresolution", "2560x1920")
            }
            switch options.aspect {
            case .gameConfig: break
            case .on: document.set("render", "aspect", "true")
            case .off: document.set("render", "aspect", "false")
            }
            if options.quietStartup {
                document.set("dosbox", "fastbioslogo", "true")
                document.set("dosbox", "startbanner", "false")
            }
        }
    }

    // MARK: - Helpers

    /// Resolves a Windows-relative config path such as `.\mt32` against `eXo/`.
    func absolutePath(_ value: String) -> String {
        if value.isEmpty { return value }
        if WindowsPath.isAbsolute(value) {
            return value.hasPrefix("/") ? value : WindowsPath.posix(value)
        }
        return WindowsPath.resolve(value, against: root.eXoDirectory).path
    }

    /// SoundFont values may be bare names (looked up by the emulator) or paths.
    func soundFontPath(_ value: String) -> String {
        if value.contains("\\") || value.contains("/") { return absolutePath(value) }
        let inLibrary = root.mt32Directory.appendingPathComponent(value)
        return FileManager.default.fileExists(atPath: inLibrary.path) ? inLibrary.path : value
    }

    static func isTrue(_ value: String) -> Bool {
        ["true", "on", "yes", "1"].contains(value.lowercased())
    }

    static func isFalse(_ value: String) -> Bool {
        ["false", "off", "no", "0"].contains(value.lowercased())
    }
}
